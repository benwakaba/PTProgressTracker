"""Export the model chosen by run_study.py to the app, and prove the export is faithful.

    .venv/bin/python export_coreml.py     # needs coremltools (see README)

Writes:
    ../PTProgressTracker/ML/RecoveryGoalClassifier.mlmodel   raw P(off track), CoreML
    ../PTProgressTracker/ML/RecoveryModelPolicy.swift        calibration + decision policy

Then reloads the .mlmodel through CoreML and checks it reproduces the Python
predictions on every test-cohort check-in, so the metrics in results/ describe
the file that ships.
"""
from __future__ import annotations

import json
from pathlib import Path

import coremltools as ct
import joblib
import numpy as np
import pandas as pd
from coremltools.models import datatypes

HERE = Path(__file__).resolve().parent
ARTIFACTS = HERE / "artifacts"
APP_ML = HERE.parent / "PTProgressTracker" / "ML"
MODEL_PATH = APP_ML / "RecoveryGoalClassifier.mlmodel"
POLICY_PATH = APP_ML / "RecoveryModelPolicy.swift"

# Same names and types RecoveryPredictor passes today.
INPUTS = [
    ("daysSinceStart", datatypes.Int64()),
    ("adherenceRatio", datatypes.Double()),
    ("avgPainLast7", datatypes.Double()),
    ("painTrend", datatypes.Double()),
    ("completionRatio", datatypes.Double()),
    ("currentStreak", datatypes.Int64()),
]
TOLERANCE = 1e-6

POLICY_TEMPLATE = """\
// GENERATED by MLTraining/export_coreml.py from the run_study.py results. Do not edit.
// Model: {candidate}, trained with scikit-learn {sklearn} on the simulated
// development cohort (seed {seed}). Test-cohort AUROC {auroc:.3f}.
// See MLTraining/README.md for what these numbers do and do not mean.

import Foundation

enum RecoveryModelPolicy {{
    /// Platt recalibration fitted on out-of-fold predictions:
    /// p' = sigmoid(a * logit(p) + b).
    static let plattA = {a!r}
    static let plattB = {b!r}

    /// Flag when calibrated P(off track) >= threshold. With calibrated
    /// probabilities, 1 / (1 + cost ratio) minimises expected cost; a missed
    /// off-track patient is weighted {cost_ratio:g}x a false alarm.
    static let decisionThreshold = {threshold!r}

    /// No card until a patient has this many days of logging history: week-1
    /// predictions are weak, and the patients they would catch are caught later.
    static let warmUpDays = {warmup}

    static func calibrated(_ probability: Double) -> Double {{
        let p = min(max(probability, 1e-6), 1 - 1e-6)
        let z = plattA * log(p / (1 - p)) + plattB
        return 1 / (1 + exp(-z))
    }}
}}
"""


def main():
    info = json.loads((ARTIFACTS / "calibration.json").read_text())
    model = joblib.load(ARTIFACTS / "final_model.joblib")
    assert [name for name, _ in INPUTS] == info["features"], "feature order changed"

    # coremltools only converts LogisticRegression with multi_class="ovr".
    # For two classes, scikit-learn's default "auto" already fits exactly that,
    # so this is a relabel; the parity check below proves nothing changed.
    classifier = model.named_steps["clf"]
    assert list(classifier.classes_) == [0, 1]
    classifier.multi_class = "ovr"

    mlmodel = ct.converters.sklearn.convert(model, INPUTS, "offTrack")
    spec = mlmodel.get_spec()
    ct.utils.rename_feature(spec, "classProbability", "offTrackProbability")
    mlmodel = ct.models.MLModel(spec)
    mlmodel.author = "PT Progress Tracker"
    mlmodel.version = "2.0"
    mlmodel.short_description = (
        "P(off track): probability the patient will not reach a 30% pain reduction by week 6. "
        "Trained on simulated patients; see MLTraining/README.md. Output is uncalibrated; apply "
        "RecoveryModelPolicy.calibrated before thresholding."
    )
    for name, _ in INPUTS:
        mlmodel.input_description[name] = f"RecoveryFeatures.{name} (MLTraining/features.py)"
    mlmodel.output_description["offTrack"] = "1 if P(off track) >= 0.5 (ignore: the app thresholds calibrated probabilities)"
    mlmodel.output_description["offTrackProbability"] = "Class probabilities; [1] is P(off track), before calibration"
    mlmodel.user_defined_metadata.update(
        {
            "training": f"{info['candidate']} on simulated development cohort, seed {info['seed']}",
            "testAUROC": f"{info['test_auroc']:.4f}",
            "plattA": repr(info["platt_a"]),
            "plattB": repr(info["platt_b"]),
            "threshold": repr(info["threshold"]),
        }
    )
    # Protobuf doesn't fix map order by default; deterministic bytes mean an
    # unchanged model re-exports without a diff.
    MODEL_PATH.write_bytes(mlmodel.get_spec().SerializeToString(deterministic=True))

    # Faithfulness: reload through CoreML and compare with scikit-learn.
    reloaded = ct.models.MLModel(str(MODEL_PATH))
    test = pd.read_csv(ARTIFACTS / "test_predictions.csv")
    worst = 0.0
    for row in test.itertuples(index=False):
        inputs = {name: (int(getattr(row, name)) if isinstance(kind, datatypes.Int64) else float(getattr(row, name))) for name, kind in INPUTS}
        p = reloaded.predict(inputs)["offTrackProbability"][1]
        worst = max(worst, abs(p - row.p_raw))
    print(f"CoreML vs scikit-learn on {len(test)} test check-ins: max |difference| = {worst:.2e}")
    assert worst < TOLERANCE, "exported model does not reproduce the evaluated one"

    POLICY_PATH.write_text(
        POLICY_TEMPLATE.format(
            candidate=info["candidate"],
            sklearn=info["sklearn"],
            seed=info["seed"],
            auroc=info["test_auroc"],
            a=info["platt_a"],
            b=info["platt_b"],
            cost_ratio=info["cost_ratio"],
            threshold=info["threshold"],
            warmup=info["warmup_days"],
        )
    )
    print(f"Wrote {MODEL_PATH.relative_to(HERE.parent)} and {POLICY_PATH.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
